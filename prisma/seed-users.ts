import { homePathFor } from "@/domain/access/dashboards";
import { ROLE_LABELS, ROLES, type Role } from "@/domain/access/roles";

/** Synthetic development/test accounts: one per role, all sharing the password in SEED_USER_PASSWORD. */
export const SEED_PASSWORD_ENV = "SEED_USER_PASSWORD";

/** Written by the development seed. Git-ignored and Docker-ignored because it contains a password. */
export const DEV_ACCOUNTS_FILE = "DEV_ACCOUNTS.md";

export function seedEmailFor(role: Role): string {
  return `${role.toLowerCase()}@example.invalid`;
}

export function seedNameFor(role: Role): string {
  return `Dev ${role.charAt(0)}${role.slice(1).toLowerCase()}`;
}

export type NamedDevAccount = { name: string; email: string; role: Role };

/**
 * Renders the sign-in cheat sheet: the role accounts, then any named accounts (for example the people
 * in the imported sales export). Pure, so a unit test can check it.
 */
export function renderDevAccountsMarkdown(
  password: string,
  baseUrl: string,
  generatedAt: Date,
  namedAccounts: readonly NamedDevAccount[] = [],
): string {
  const named =
    namedAccounts.length === 0
      ? []
      : [
          "## Named accounts",
          "",
          "People from the imported sales export, one account each. Same password as above.",
          "",
          "| Name | Role | Email | Lands on |",
          "|---|---|---|---|",
          ...namedAccounts.map((a) => `| ${a.name} | ${ROLE_LABELS[a.role]} | \`${a.email}\` | \`${homePathFor(a.role)}\` |`),
          "",
        ];
  const rows = ROLES.map(
    (role) =>
      `| ${ROLE_LABELS[role]} | \`${seedEmailFor(role)}\` | \`${password}\` | \`${homePathFor(role)}\` |`,
  );
  return [
    "# Development accounts",
    "",
    "> **Local development only. Do not commit this file.** It is listed in `.gitignore` and `.dockerignore`",
    "> because it contains a password. The accounts are synthetic and exist only in the development database.",
    "",
    `Open ${baseUrl}/login and sign in with any account below.`,
    "",
    "| Role | Email | Password | Lands on |",
    "|---|---|---|---|",
    ...rows,
    "",
    ...named,
    "Notes:",
    "",
    `- Generated by \`npm run db:seed\` on ${generatedAt.toISOString().slice(0, 16).replace("T", " ")} UTC.`,
    `- The password is the value of \`${SEED_PASSWORD_ENV}\` in \`.env\` at that moment.`,
    "- The seed never overwrites existing users. If a password was reset on the Users page, or",
    `  \`${SEED_PASSWORD_ENV}\` changed after the accounts were created, this file can be out of date.`,
    "- Superadmin also sees the System page and the theme switcher; Admin can manage the operational users.",
    "",
  ].join("\n");
}
