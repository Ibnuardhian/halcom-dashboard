"use client";

import { useActionState, useState } from "react";
import { Button } from "@/components/ui/button";
import { FormStatus, type FormState } from "@/components/ui/form-status";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { NativeSelect } from "@/components/ui/native-select";
import { Textarea } from "@/components/ui/textarea";
import { PROGRESS_LABELS, PROJECT_PROGRESSES, TRACK_STATUSES, TRACK_STATUS_LABELS } from "@/domain/projects/progress";
import { SOA_PHASES, SOA_PHASE_LABELS, type SoaPhase } from "@/domain/requests/phase";
import { reasonRequired, REQUEST_STATUS_LABELS, type RequestStatus } from "@/domain/requests/status";
import { OWNING_TEAM_LABELS, REQUEST_TYPE_LABELS, type RequestType } from "@/domain/requests/types";
import { changeStatusAction, createProjectAction, createRequestAction, handOverAction, setPhaseAction } from "./actions";

function Field({ id, label, hint, children }: { id: string; label: string; hint?: string; children: React.ReactNode }) {
  return (
    <div className="flex flex-col gap-1.5">
      <Label htmlFor={id}>{label}</Label>
      {children}
      {hint ? <p className="text-xs text-muted-foreground">{hint}</p> : null}
    </div>
  );
}

/**
 * `submissionKey` is generated by the server for each page view. Sending the same form twice (a
 * double click, a retried request) therefore creates one record, not two.
 */
export function ProjectForm({ submissionKey, defaultType = "" }: { submissionKey: string; defaultType?: RequestType | "" }) {
  const [state, formAction, pending] = useActionState<FormState, FormData>(createProjectAction, null);
  const [type, setType] = useState<RequestType | "">(defaultType);

  return (
    <form action={formAction} className="grid gap-4 sm:grid-cols-2">
      <input type="hidden" name="submissionKey" value={submissionKey} />
      <Field id="project-company" label="End-user company *">
        <Input id="project-company" name="endUserCompany" required maxLength={120} placeholder="PT ABC" />
      </Field>
      <Field id="project-name" label="Project name *">
        <Input id="project-name" name="name" required maxLength={120} placeholder="CCTV AI" />
      </Field>
      <Field id="project-target" label="Target closing" hint="Optional.">
        <Input id="project-target" name="targetDate" type="date" />
      </Field>
      <Field id="project-progress" label="Progress" hint="Each step stands for a win probability.">
        <NativeSelect id="project-progress" name="progress" defaultValue="QUALIFY">
          {PROJECT_PROGRESSES.map((option) => (
            <option key={option} value={option}>
              {PROGRESS_LABELS[option]}
            </option>
          ))}
        </NativeSelect>
      </Field>
      <Field id="project-status" label="Status">
        <NativeSelect id="project-status" name="trackStatus" defaultValue="ON_TRACK">
          {TRACK_STATUSES.map((option) => (
            <option key={option} value={option}>
              {TRACK_STATUS_LABELS[option]}
            </option>
          ))}
        </NativeSelect>
      </Field>
      <Field id="project-value" label="Estimated PO value" hint="Optional. Plain number, for example 1200000000.">
        <Input id="project-value" name="estimatedValue" inputMode="decimal" maxLength={40} />
      </Field>
      <Field id="project-margin" label="Target margin (%)" hint="Optional. Percentage of the sale, for example 12.5.">
        <Input id="project-margin" name="targetMargin" inputMode="decimal" maxLength={6} />
      </Field>
      <div className="sm:col-span-2">
        <Field id="project-description" label="Description" hint="Optional. Context for the team, up to 2000 characters.">
          <Textarea id="project-description" name="description" maxLength={2000} />
        </Field>
      </div>

      <fieldset className="flex flex-col gap-3 rounded-lg border p-4 sm:col-span-2">
        <legend className="px-1 text-sm font-semibold">Request for this project</legend>
        <p className="text-xs text-muted-foreground">Choose what the project needs now: a BOQ goes to SOA; an RFQ or a PO goes to Purchasing. It is created together with the project, and you can add more later from the project page.</p>
        <div className="flex flex-wrap gap-2">
          {(["", ...REQUEST_TYPE_CHOICES] as const).map((option) => (
            <label
              key={option || "none"}
              className="cursor-pointer rounded-md border px-3 py-1.5 text-sm font-medium has-[:checked]:border-primary has-[:checked]:bg-primary has-[:checked]:text-primary-foreground has-[:focus-visible]:ring-2 has-[:focus-visible]:ring-ring"
            >
              <input type="radio" name="requestType" value={option} checked={type === option} onChange={() => setType(option)} className="sr-only" />
              {option === "" ? "No request yet" : `${option} – ${REQUEST_TYPE_LABELS[option]}`}
            </label>
          ))}
        </div>
        {type ? (
          <div className="grid gap-4 sm:grid-cols-2">
            <p className="text-xs text-muted-foreground sm:col-span-2">Goes to {OWNING_TEAM_LABELS[type]}.</p>
            <div className="sm:col-span-2">
              <Field id="project-request-title" label="Request summary *" hint="One line that tells the team what is needed.">
                <Input id="project-request-title" name="requestTitle" required maxLength={150} />
              </Field>
            </div>
            <div className="sm:col-span-2">
              <Field id="project-request-details" label="Request details" hint="Known specifications, quantities, brands, constraints. Up to 4000 characters.">
                <Textarea id="project-request-details" name="requestDescription" maxLength={4000} className="min-h-28" />
              </Field>
            </div>
            <Field id="project-request-needed" label="Needed by" hint="Optional.">
              <Input id="project-request-needed" name="requestRequiredBy" type="date" />
            </Field>
          </div>
        ) : null}
      </fieldset>

      <div className="flex flex-col gap-2 sm:col-span-2">
        <FormStatus state={state} />
        <div>
          <Button type="submit" disabled={pending}>
            {pending ? "Creating…" : type ? `Create project and ${type} request` : "Create project"}
          </Button>
        </div>
      </div>
    </form>
  );
}

const REQUEST_TYPE_CHOICES = ["BOQ", "RFQ", "PO"] as const satisfies readonly RequestType[];

export type ProjectOption = { id: string; code: string; endUserCompany: string; name: string };

export function RequestForm({
  projects,
  defaultProjectId,
  defaultType,
  types,
  submissionKey,
}: {
  projects: ProjectOption[];
  defaultProjectId: string;
  defaultType: RequestType;
  types: readonly RequestType[];
  submissionKey: string;
}) {
  const [state, formAction, pending] = useActionState<FormState, FormData>(createRequestAction, null);
  const [type, setType] = useState<RequestType>(defaultType);

  return (
    <form action={formAction} className="grid gap-4 sm:grid-cols-2">
      <input type="hidden" name="submissionKey" value={submissionKey} />
      <Field id="request-project" label="Project *">
        <NativeSelect id="request-project" name="projectId" required defaultValue={defaultProjectId}>
          <option value="" disabled>
            Select a project
          </option>
          {projects.map((project) => (
            <option key={project.id} value={project.id}>
              {project.code} · {project.endUserCompany} – {project.name}
            </option>
          ))}
        </NativeSelect>
      </Field>
      <Field id="request-type" label="Request type *" hint={`Goes to ${OWNING_TEAM_LABELS[type]}.`}>
        <NativeSelect id="request-type" name="type" required value={type} onChange={(event) => setType(event.target.value as RequestType)}>
          {types.map((option) => (
            <option key={option} value={option}>
              {option} – {REQUEST_TYPE_LABELS[option]}
            </option>
          ))}
        </NativeSelect>
      </Field>
      <div className="sm:col-span-2">
        <Field id="request-title" label="Summary *" hint="One line that tells the team what is needed.">
          <Input id="request-title" name="title" required maxLength={150} />
        </Field>
      </div>
      <div className="sm:col-span-2">
        <Field id="request-description" label="Details" hint="Known specifications, quantities, brands, constraints. Up to 4000 characters.">
          <Textarea id="request-description" name="description" maxLength={4000} className="min-h-32" />
        </Field>
      </div>
      <Field id="request-needed" label="Needed by" hint="Optional.">
        <Input id="request-needed" name="requiredBy" type="date" />
      </Field>
      <div className="flex flex-col gap-2 sm:col-span-2">
        <FormStatus state={state} />
        <div>
          <Button type="submit" disabled={pending || projects.length === 0}>
            {pending ? "Submitting…" : "Create request"}
          </Button>
        </div>
      </div>
    </form>
  );
}

export function StatusForm({ requestId, from, options }: { requestId: string; from: RequestStatus; options: readonly RequestStatus[] }) {
  const [state, formAction, pending] = useActionState<FormState, FormData>(changeStatusAction, null);
  const [to, setTo] = useState<RequestStatus>(options[0]!);
  const needsReason = reasonRequired(from, to);

  return (
    <form action={formAction} className="grid gap-3 sm:grid-cols-[minmax(0,14rem)_1fr_auto] sm:items-end">
      <input type="hidden" name="requestId" value={requestId} />
      <Field id={`status-${requestId}`} label="Change status to">
        <NativeSelect id={`status-${requestId}`} name="to" value={to} onChange={(event) => setTo(event.target.value as RequestStatus)}>
          {options.map((option) => (
            <option key={option} value={option}>
              {REQUEST_STATUS_LABELS[option]}
            </option>
          ))}
        </NativeSelect>
      </Field>
      <Field id={`reason-${requestId}`} label={needsReason ? "Reason *" : "Reason (optional)"}>
        <Input id={`reason-${requestId}`} name="reason" maxLength={500} required={needsReason} placeholder={needsReason ? "Required for this change" : ""} />
      </Field>
      <Button type="submit" disabled={pending}>
        {pending ? "Saving…" : "Update status"}
      </Button>
      <div className="sm:col-span-3">
        <FormStatus state={state} />
      </div>
    </form>
  );
}

/** SOA picks RFQ or PO explicitly; a completed BOQ never implies a purchase (brief §6.1). */
export function HandoverForm({ sourceId }: { sourceId: string }) {
  const [state, formAction, pending] = useActionState<FormState, FormData>(handOverAction, null);

  return (
    <form action={formAction} className="flex flex-col gap-3">
      <input type="hidden" name="sourceId" value={sourceId} />
      <div className="flex flex-wrap gap-2">
        <Button type="submit" name="targetType" value="RFQ" disabled={pending}>
          Hand over as RFQ (quotation / pricing)
        </Button>
        <Button type="submit" name="targetType" value="PO" variant="outline" disabled={pending}>
          Hand over as PO (purchase)
        </Button>
      </div>
      <FormStatus state={state} />
    </form>
  );
}

/** SOA labels the part of the BOQ work they are on. */
